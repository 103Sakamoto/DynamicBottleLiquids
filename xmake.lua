set_xmakever("3.0.0")
set_project("DynamicBottleLiquids")
set_version("1.0.0")
set_languages("c++23")
set_arch("x64")
set_toolchains("msvc")
set_runtimes("MD")
add_defines("NOMINMAX", "WIN32_LEAN_AND_MEAN")
add_rules("mode.debug", "mode.release", "mode.releasedbg")
includes(".deps/CommonLibF4")
add_requires("minhook 1.3.4", {system = false})
target("DynamicBottleLiquids", function()
    set_kind("shared")
    set_targetdir("build/bin")
    add_deps("commonlibf4")
    add_packages("minhook")
    add_includedirs("native/src")
    add_files("native/src/*.cpp")
    add_syslinks("d3d11", "d3dcompiler", "dxgi", "user32", "gdi32")
    add_cxxflags("/EHsc", "/Zc:preprocessor", "/bigobj")
    set_pcxxheader("native/src/PCH.h")
end)

target("ProfileTests", function()
    set_kind("binary")
    set_default(false)
    set_targetdir("build/tests")
    add_deps("commonlibf4")
    add_includedirs("native/src")
    add_files("tests/ProfileTests.cpp", "native/src/Profiles.cpp", "native/src/Simulation.cpp")
    add_cxxflags("/EHsc", "/Zc:preprocessor", "/bigobj")
end)
